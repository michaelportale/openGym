#!/usr/bin/env node
// Writes src/theme/theme-<name>.css for every palette in src/theme/palettes.json.
//
//   node scripts/gen-palettes.mjs          write the files
//   node scripts/gen-palettes.mjs --check  exit 1 if a file is missing or out of date
//
// palettes.json is the single source of truth: change a colour there and re-run. The light-mode
// values are not in the JSON (the palettes are dark-first); they are derived here with the same
// contrast maths the app uses for a user's own accent (src/lib/accent.js), so an accent or status
// colour that would vanish on a white card is darkened just far enough to read.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { readableIn, mix, inkOn, inkOnBoth, contrast } from '../src/lib/accent.js'

const here = dirname(fileURLToPath(import.meta.url))
const themeDir = join(here, '..', 'src', 'theme')
const KNOB_RING = 'rgba(0,0,0,.28)'

export function loadPalettes(file = join(themeDir, 'palettes.json')) {
  return JSON.parse(readFileSync(file, 'utf8'))
}

const lc = h => h.toLowerCase()
const decl = vars => Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')
const block = (sel, vars) => `${sel} {\n${decl(vars)}\n}\n`

/** The CSS text for one palette. Pure: same input, same output. */
export function paletteCss(p) {
  const t = Object.fromEntries(Object.entries(p.tokens).map(([k, v]) => [k, lc(v)]))
  const id = p.name
  const neutrals = {
    '--bg': t.bg0, '--bg-el': t.bg1,
    '--surface': t.surface, '--surface-2': t.surface2, '--surface-3': t.surface3,
    '--label': t.text1, '--label-2': t.text2, '--label-3': t.text3,
    '--label-4': `color-mix(in srgb, ${t.text1} 18%, transparent)`,
    '--sep': t.line, '--sep-op': `color-mix(in srgb, ${t.line} 70%, transparent)`,
  }
  const status = {
    '--success': t.success, '--on-success': inkOn(mix(t.success, t.surface, 0.3)),
    '--warning': t.warning, '--danger': t.danger, '--pr': t.pr,
    // the glyph on a tile filled with the status colour (.lrow-i)
    '--on-success-tile': inkOn(t.success), '--on-warning-tile': inkOn(t.warning),
  }
  const accDark = {
    '--acc': t.accent, '--acc-2': t.accentPressed, '--on-acc': t.onAccent, '--on-acc-tile': t.onAccent,
    '--knob-ring': contrast('#ffffff', t.accent) < 1.5 ? KNOB_RING : 'transparent',
  }
  // Light mode keeps the app's light surfaces; only colours that sit on them are adjusted.
  const accL = readableIn(t.accent, 'light'), accL2 = mix(accL, '#000000', 0.25)
  const statusLight = {}
  for (const k of ['success', 'warning', 'danger', 'pr']) statusLight['--' + k] = readableIn(t[k], 'light')
  statusLight['--on-success'] = inkOn(mix(statusLight['--success'], '#ffffff', 0.3))
  statusLight['--on-success-tile'] = inkOn(statusLight['--success'])
  statusLight['--on-warning-tile'] = inkOn(statusLight['--warning'])
  const accLight = {
    '--acc': accL, '--acc-2': accL2, '--on-acc': inkOnBoth(accL, accL2), '--on-acc-tile': inkOn(accL),
    '--knob-ring': contrast('#ffffff', accL) < 1.5 ? KNOB_RING : 'transparent',
  }
  return `/* ${p.label} (${id}). GENERATED by scripts/gen-palettes.mjs from palettes.json; edit
   the JSON and re-run instead of editing this file. Loaded after every other stylesheet.
   ${p.vibe}
   Success: ${p.successTreatment} */

/* dark: the palette's own neutrals and status colours */
${block(`:root[data-theme="${id}"]`, { ...neutrals, ...status })}
/* the workout screen tints its neutrals (views/WorkoutLedger.css); the palette's win here too */
${block(`:root[data-theme="${id}"] body.no-tabbar`, neutrals)}
/* accent, only while the accent setting is "palette" (a preset or own colour still wins) */
${block(`:root[data-theme="${id}"][data-accent="theme"]`, { ...accDark, '--acc-soft': t.accentMuted })}
/* light: the app's light surfaces, with this palette's colours made readable on them */
${block(`:root[data-theme="light"][data-palette="${id}"]`, statusLight)}
${block(`:root[data-theme="light"][data-palette="${id}"][data-accent="theme"]`, accLight)}`
}

export function outputs(data = loadPalettes()) {
  return data.palettes.map(p => ({ file: join(themeDir, `theme-${p.name}.css`), css: paletteCss(p) }))
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const { file, css } of outputs()) {
    const cur = existsSync(file) ? readFileSync(file, 'utf8') : null
    if (cur === css) continue
    if (check) { console.error(`out of date: ${file}`); stale++ } else { writeFileSync(file, css); console.log(`wrote ${file}`) }
  }
  if (check && stale) process.exit(1)
  if (check) console.log('palette CSS in sync with palettes.json')
}
